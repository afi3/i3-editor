//! Commands are the only way to mutate application state.

use std::path::PathBuf;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Move {
    Left,
    Right,
    WordLeft,
    WordRight,
    Up,
    Down,
    LineStart,
    LineEnd,
    PageUp,
    PageDown,
    DocStart,
    DocEnd,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Direction {
    Left,
    Right,
    Up,
    Down,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Command {
    Quit,
    Save,
    SavePrompt,
    OpenPrompt,
    NewPrompt,
    CloseDocument,
    ToggleExplorer,
    QuickOpen,
    Palette,
    GoToLinePrompt,
    FindPrompt,
    ReplacePrompt,
    NextDocument,
    PrevDocument,
    NextMatch,
    Undo,
    Redo,
    SelectAll,
    Copy,
    Cut,
    Paste,
    DuplicateLine,
    InsertText(String),
    InsertNewline,
    Backspace,
    DeleteForward,
    MoveCursor(Move),
    ExtendSelection(Move),
    FocusPane(Direction),
    MovePane(Direction),
    ToggleMoveMode,
    ExplorerUp,
    ExplorerDown,
    ExplorerSelect,
    ExplorerExpand,
    ExplorerCollapse,
    ExplorerNewFile,
    ExplorerNewDir,
    ExplorerRename,
    ExplorerDelete,
    ExplorerRefresh,
    ExplorerToggleHidden,
    SplitLeftRight,
    SplitTopBottom,
    ClosePane,
    ToggleFullscreen,
    ToggleTabbed,
    NextPaneTab,
    PrevPaneTab,
    ToggleTerminal,
    SelectTheme,
    NextTheme,
    PrevTheme,
    NewWorkspace,
    CloseWorkspace,
    SwitchWorkspace(usize),
    SaveTo(PathBuf),
    CreateFile(PathBuf),
    CreateDir(PathBuf),
    RenameTo(PathBuf),
    DeleteTarget(PathBuf),
}

